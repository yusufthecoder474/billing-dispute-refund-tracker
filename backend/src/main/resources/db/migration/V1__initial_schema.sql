CREATE TABLE app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(254) NOT NULL UNIQUE, password_hash VARCHAR(100) NOT NULL,
 display_name VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK (role IN ('CUSTOMER','SUPPORT','MANAGER')),
 created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE disputes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id BIGINT NOT NULL REFERENCES app_users(id),
 assigned_support_id BIGINT REFERENCES app_users(id),
 category VARCHAR(40) NOT NULL CHECK (category IN ('DUPLICATE_CHARGE','INCORRECT_AMOUNT','UNEXPECTED_FEE','BILLING_ADJUSTMENT')),
 description VARCHAR(2000) NOT NULL,
 disputed_amount NUMERIC(12,2) NOT NULL CHECK (disputed_amount > 0),
 currency VARCHAR(3) NOT NULL DEFAULT 'INR' CHECK (currency = 'INR'),
 status VARCHAR(30) NOT NULL CHECK (status IN ('OPEN','IN_REVIEW','PENDING_DECISION','RESOLVED_APPROVED','RESOLVED_REJECTED')),
 created_at TIMESTAMPTZ NOT NULL, due_at TIMESTAMPTZ NOT NULL,
 resolved_at TIMESTAMPTZ, version BIGINT NOT NULL DEFAULT 0,
 CHECK (due_at = created_at + INTERVAL '72 hours'),
 CHECK ((status IN ('RESOLVED_APPROVED','RESOLVED_REJECTED')) = (resolved_at IS NOT NULL))
);
CREATE TABLE dispute_decisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dispute_id BIGINT NOT NULL UNIQUE REFERENCES disputes(id),
 manager_id BIGINT NOT NULL REFERENCES app_users(id),
 outcome VARCHAR(20) NOT NULL CHECK (outcome IN ('APPROVED','REJECTED')),
 approved_refund_amount NUMERIC(12,2) NOT NULL CHECK (approved_refund_amount >= 0),
 explanation VARCHAR(2000) NOT NULL, created_at TIMESTAMPTZ NOT NULL,
 CHECK (outcome <> 'REJECTED' OR approved_refund_amount = 0)
);
CREATE TABLE audit_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dispute_id BIGINT NOT NULL REFERENCES disputes(id), actor_id BIGINT NOT NULL REFERENCES app_users(id),
 action VARCHAR(40) NOT NULL, previous_status VARCHAR(30), new_status VARCHAR(30) NOT NULL,
 detail VARCHAR(500) NOT NULL, created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_customer_history ON disputes(customer_id, created_at DESC);
CREATE INDEX idx_support_queue ON disputes(assigned_support_id, status, due_at);
CREATE INDEX idx_status_deadline ON disputes(status, due_at);
CREATE INDEX idx_created_report ON disputes(created_at);
CREATE INDEX idx_resolved_report ON disputes(resolved_at) WHERE resolved_at IS NOT NULL;
CREATE INDEX idx_audit_timeline ON audit_events(dispute_id, created_at, id);
